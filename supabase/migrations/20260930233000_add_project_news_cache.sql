create table public.project_news_articles (
  id bigint generated by default as identity primary key,
  project_id text not null references public.projects(id) on delete cascade,
  title text not null check (length(trim(title)) between 4 and 500),
  url text not null check (url ~* '^https?://'),
  publisher text,
  published_at timestamptz,
  discovered_at timestamptz not null default now(),
  source_query text,
  evidence_excerpt text,
  match_confidence numeric(4, 3) not null default 0.800
    check (match_confidence between 0 and 1),
  review_status text not null default 'pending'
    check (review_status in ('pending', 'approved', 'rejected')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  review_note text,
  dedupe_fingerprint text not null unique,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index project_news_articles_project_status_date_idx
  on public.project_news_articles (
    project_id,
    review_status,
    published_at desc nulls last,
    discovered_at desc
  );

create index project_news_articles_review_date_idx
  on public.project_news_articles (
    review_status,
    discovered_at desc
  );

alter table public.project_news_articles enable row level security;

revoke all on table public.project_news_articles from public, anon, authenticated;
revoke all on sequence public.project_news_articles_id_seq from public, anon, authenticated;

grant select on table public.project_news_articles to anon, authenticated;
grant update (review_status, reviewed_by, reviewed_at, review_note, updated_at)
  on table public.project_news_articles to authenticated;
grant select, insert, update, delete on table public.project_news_articles to service_role;
grant usage, select on sequence public.project_news_articles_id_seq to service_role;

create policy public_can_read_approved_project_news
  on public.project_news_articles
  for select
  to anon, authenticated
  using (review_status = 'approved');

create policy admins_can_read_all_project_news
  on public.project_news_articles
  for select
  to authenticated
  using ((select private.is_tracker_admin()));

create policy admins_can_review_project_news
  on public.project_news_articles
  for update
  to authenticated
  using ((select private.is_tracker_admin()))
  with check ((select private.is_tracker_admin()));

create or replace function public.review_project_news_article(
  p_article_id bigint,
  p_decision text,
  p_note text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  article public.project_news_articles%rowtype;
  decision text := lower(trim(p_decision));
begin
  if (select auth.uid()) is null or not private.is_tracker_admin() then
    raise exception 'Approved tracker administrator access is required.';
  end if;

  if decision not in ('approve', 'reject') then
    raise exception 'Decision must be approve or reject.';
  end if;

  select *
    into article
  from public.project_news_articles
  where id = p_article_id
  for update;

  if not found then
    raise exception 'Project news article was not found.';
  end if;

  update public.project_news_articles
  set review_status = case when decision = 'approve' then 'approved' else 'rejected' end,
      reviewed_by = (select auth.uid()),
      reviewed_at = now(),
      review_note = nullif(trim(p_note), ''),
      updated_at = now()
  where id = article.id;

  return jsonb_build_object(
    'article_id', article.id,
    'project_id', article.project_id,
    'status', case when decision = 'approve' then 'approved' else 'rejected' end
  );
end;
$$;

revoke all on function public.review_project_news_article(bigint, text, text)
  from public, anon;
grant execute on function public.review_project_news_article(bigint, text, text)
  to authenticated;

create or replace function public.get_project_news_status(p_project_id text)
returns table (
  project_id text,
  last_checked_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select state.project_id, state.last_checked_at
  from private.project_monitoring_state state
  join public.projects project on project.id = state.project_id
  where state.project_id = p_project_id
    and project.is_published = true;
$$;

revoke all on function public.get_project_news_status(text) from public;
grant execute on function public.get_project_news_status(text) to anon, authenticated;

notify pgrst, 'reload schema';

create table public.transit_routes (
  id bigint generated by default as identity primary key,
  slug text not null unique
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null
    check (length(btrim(name)) between 2 and 120),
  mode text not null
    check (mode in ('BRT', 'ART')),
  color text not null
    check (color ~ '^#[0-9A-Fa-f]{6}$'),
  dash_array text not null default '10 7'
    check (length(btrim(dash_array)) between 3 and 30),
  geometry jsonb not null
    check (
      jsonb_typeof(geometry) = 'object'
      and geometry ->> 'type' in ('LineString', 'MultiLineString')
      and jsonb_typeof(geometry -> 'coordinates') = 'array'
    ),
  miles numeric(9, 2) not null
    check (miles > 0 and miles < 1000),
  source_filename text
    check (source_filename is null or length(source_filename) <= 255),
  sort_order integer not null default 0,
  is_published boolean not null default true,
  created_by uuid not null default auth.uid()
    references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index transit_routes_name_ci_key
  on public.transit_routes (lower(name));

create index transit_routes_published_sort_idx
  on public.transit_routes (is_published, sort_order, name);

comment on table public.transit_routes is
  'Admin-uploaded BRT and ART alignments normalized to GeoJSON for the public map.';

alter table public.transit_routes enable row level security;

revoke all on table public.transit_routes
  from public, anon, authenticated;
grant select on table public.transit_routes
  to anon, authenticated;
grant insert, update, delete on table public.transit_routes
  to authenticated;

revoke all on sequence public.transit_routes_id_seq
  from public, anon, authenticated;
grant usage, select on sequence public.transit_routes_id_seq
  to authenticated;

create policy anonymous_can_read_published_transit_routes
  on public.transit_routes
  for select
  to anon
  using (is_published);

create policy authenticated_transit_route_read_access
  on public.transit_routes
  for select
  to authenticated
  using (
    is_published
    or (select private.is_tracker_admin())
  );

create policy admins_can_insert_transit_routes
  on public.transit_routes
  for insert
  to authenticated
  with check (
    (select private.is_tracker_admin())
    and created_by = (select auth.uid())
  );

create policy admins_can_update_transit_routes
  on public.transit_routes
  for update
  to authenticated
  using ((select private.is_tracker_admin()))
  with check ((select private.is_tracker_admin()));

create policy admins_can_delete_transit_routes
  on public.transit_routes
  for delete
  to authenticated
  using ((select private.is_tracker_admin()));

